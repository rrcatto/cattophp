<?php

declare(strict_types=1);

namespace CattoPHP\Schema\Steps;

use CattoPHP\Schema\SqlStep;

/**
 * The Campaign Marketing Manager's sales and connected sites: each order a project reports (or a connected site reports),
 * with its lines and its money as it happened (paid, each refund, each chargeback, each kept once by its own key), and
 * which campaign gets it, fixed when it is paid; the other sites this one is connected to, with the reports waiting to go
 * to them and those received from them. Visitors gain a reference (their address, and their name until they are known;
 * those already there are given one), touches a reference for every new click and the publication code of an arrival
 * from a connected site, campaigns the connected site one was made for by an arrival, and the journey's events the sale
 * they belong to. Money is whole minor units; a person is their account in text; no IP address is kept by any of these.
 */
final class Step202611141200MarketingSales extends SqlStep
{
    public function id(): string
    {
        return '202611141200-marketing-sales';
    }

    public function describe(): string
    {
        return 'The Campaign Marketing Manager: sales, their lines and money, connected sites and their reports, and references for visitors and touches';
    }

    protected function statements(): array
    {
        return [
            // Visitors: a reference, never the cookie's token, given to every visitor already there.
            'ALTER TABLE cattophp_marketing_visitors ADD COLUMN reference varchar(12) NULL',
            'DO $$
            DECLARE
                letters constant text := \'abcdefghjkmnpqrstuvwxyz23456789\';
                visitor record;
                made text;
            BEGIN
                FOR visitor IN SELECT id FROM cattophp_marketing_visitors WHERE reference IS NULL ORDER BY id LOOP
                    LOOP
                        made := \'\';
                        FOR i IN 1..8 LOOP
                            made := made || substr(letters, 1 + floor(random() * length(letters))::integer, 1);
                        END LOOP;
                        EXIT WHEN NOT EXISTS (SELECT 1 FROM cattophp_marketing_visitors WHERE reference = made);
                    END LOOP;
                    UPDATE cattophp_marketing_visitors SET reference = made WHERE id = visitor.id;
                END LOOP;
            END $$',
            'ALTER TABLE cattophp_marketing_visitors ALTER COLUMN reference SET NOT NULL',
            'ALTER TABLE cattophp_marketing_visitors ADD CONSTRAINT cattophp_marketing_visitors_reference_key UNIQUE (reference)',
            'ALTER TABLE cattophp_marketing_visitors ADD CONSTRAINT cattophp_marketing_visitors_reference CHECK (reference ~ \'^[a-z0-9]{8,10}$\')',
            // Touches: a reference for each new one (older touches have none), and an arrival's publication on the other site.
            'ALTER TABLE cattophp_marketing_touches ADD COLUMN reference varchar(12) NULL',
            'ALTER TABLE cattophp_marketing_touches ADD CONSTRAINT cattophp_marketing_touches_reference_key UNIQUE (reference)',
            'ALTER TABLE cattophp_marketing_touches ADD CONSTRAINT cattophp_marketing_touches_reference CHECK (reference IS NULL OR reference ~ \'^[a-z0-9]{8,10}$\')',
            'ALTER TABLE cattophp_marketing_touches ADD COLUMN origin_publication varchar(12) NULL',
            // Campaigns: the connected site a campaign was made for by an arrival; null for one made here.
            'ALTER TABLE cattophp_marketing_campaigns ADD COLUMN origin_site varchar(40) NULL',
            'CREATE TABLE cattophp_marketing_sales (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reference varchar(60) NOT NULL CHECK (reference ~ \'^[^[:space:]]{1,60}$\'),
                origin_site varchar(40) NULL,
                account text NULL,
                organisation varchar(120) NULL,
                visitor_id bigint NULL REFERENCES cattophp_marketing_visitors(id) ON DELETE SET NULL,
                country varchar(2) NOT NULL DEFAULT \'\',
                state varchar(10) NOT NULL DEFAULT \'waiting\' CHECK (state IN (\'waiting\', \'paid\', \'cancelled\')),
                currency char(3) NOT NULL CHECK (currency ~ \'^[A-Z]{3}$\'),
                list_minor bigint NOT NULL DEFAULT 0 CHECK (list_minor >= 0),
                discount_minor bigint NOT NULL DEFAULT 0 CHECK (discount_minor >= 0),
                total_minor bigint NOT NULL DEFAULT 0 CHECK (total_minor >= 0),
                wallet_minor bigint NOT NULL DEFAULT 0 CHECK (wallet_minor >= 0),
                paid_minor bigint NOT NULL DEFAULT 0 CHECK (paid_minor >= 0),
                refunded_minor bigint NOT NULL DEFAULT 0 CHECK (refunded_minor >= 0),
                charged_back_minor bigint NOT NULL DEFAULT 0 CHECK (charged_back_minor >= 0),
                promotion varchar(120) NULL,
                placed_at timestamptz NOT NULL,
                paid_at timestamptz NULL,
                cancelled_at timestamptz NULL,
                updated_at timestamptz NOT NULL DEFAULT now(),
                first_touch_id bigint NULL REFERENCES cattophp_marketing_touches(id) ON DELETE SET NULL,
                last_touch_id bigint NULL REFERENCES cattophp_marketing_touches(id) ON DELETE SET NULL,
                first_campaign_id bigint NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE SET NULL,
                last_campaign_id bigint NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE SET NULL,
                first_publication_id bigint NULL REFERENCES cattophp_marketing_publications(id) ON DELETE SET NULL,
                last_publication_id bigint NULL REFERENCES cattophp_marketing_publications(id) ON DELETE SET NULL,
                first_by varchar(10) NULL CHECK (first_by IS NULL OR first_by IN (\'link\', \'promotion\', \'site\')),
                last_by varchar(10) NULL CHECK (last_by IS NULL OR last_by IN (\'link\', \'promotion\', \'site\')),
                promotion_campaign_id bigint NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE SET NULL,
                promotion_counts varchar(10) NULL CHECK (promotion_counts IS NULL OR promotion_counts IN (\'no_link\', \'always\')),
                counted_within varchar(20) NULL,
                attributed_at timestamptz NULL,
                fixed boolean NOT NULL DEFAULT false,
                CONSTRAINT cattophp_marketing_sales_reference_key UNIQUE NULLS NOT DISTINCT (origin_site, reference),
                CONSTRAINT cattophp_marketing_sales_wallet CHECK (wallet_minor <= total_minor),
                CONSTRAINT cattophp_marketing_sales_taken_back CHECK (refunded_minor + charged_back_minor <= paid_minor),
                CONSTRAINT cattophp_marketing_sales_paid_when CHECK ((state = \'paid\') = (paid_at IS NOT NULL)),
                CONSTRAINT cattophp_marketing_sales_paid_only CHECK (state = \'paid\' OR (paid_minor = 0 AND refunded_minor = 0 AND charged_back_minor = 0)),
                CONSTRAINT cattophp_marketing_sales_cancelled_when CHECK (state <> \'cancelled\' OR cancelled_at IS NOT NULL),
                CONSTRAINT cattophp_marketing_sales_fixed_when_paid CHECK (NOT fixed OR state = \'paid\')
            )',
            'CREATE INDEX cattophp_marketing_sales_paid_idx ON cattophp_marketing_sales (paid_at)',
            'CREATE INDEX cattophp_marketing_sales_state_idx ON cattophp_marketing_sales (state, placed_at)',
            'CREATE INDEX cattophp_marketing_sales_first_campaign_idx ON cattophp_marketing_sales (first_campaign_id, paid_at)',
            'CREATE INDEX cattophp_marketing_sales_last_campaign_idx ON cattophp_marketing_sales (last_campaign_id, paid_at)',
            'CREATE INDEX cattophp_marketing_sales_account_idx ON cattophp_marketing_sales (account) WHERE account IS NOT NULL',
            'CREATE INDEX cattophp_marketing_sales_organisation_idx ON cattophp_marketing_sales (organisation) WHERE organisation IS NOT NULL',
            'CREATE INDEX cattophp_marketing_sales_visitor_idx ON cattophp_marketing_sales (visitor_id) WHERE visitor_id IS NOT NULL',
            'CREATE TABLE cattophp_marketing_sale_lines (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                sale_id bigint NOT NULL REFERENCES cattophp_marketing_sales(id) ON DELETE CASCADE,
                line_key varchar(120) NOT NULL CHECK (line_key <> \'\'),
                offer_type varchar(40) NOT NULL CHECK (offer_type <> \'\'),
                offer_reference varchar(120) NOT NULL CHECK (offer_reference <> \'\'),
                label varchar(200) NOT NULL,
                kind_label varchar(60) NOT NULL DEFAULT \'\',
                quantity integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
                price_minor bigint NOT NULL CHECK (price_minor >= 0),
                was_minor bigint NULL CHECK (was_minor IS NULL OR was_minor >= 0),
                discount_minor bigint NOT NULL DEFAULT 0 CHECK (discount_minor >= 0),
                paid_minor bigint NOT NULL CHECK (paid_minor >= 0),
                wallet_minor bigint NOT NULL DEFAULT 0 CHECK (wallet_minor >= 0),
                refunded_minor bigint NOT NULL DEFAULT 0 CHECK (refunded_minor >= 0),
                charged_back_minor bigint NOT NULL DEFAULT 0 CHECK (charged_back_minor >= 0),
                contains jsonb NOT NULL DEFAULT \'[]\'::jsonb CHECK (jsonb_typeof(contains) = \'array\'),
                position integer NOT NULL DEFAULT 0,
                CONSTRAINT cattophp_marketing_sale_lines_key UNIQUE (sale_id, line_key),
                CONSTRAINT cattophp_marketing_sale_lines_paid CHECK (paid_minor = price_minor - discount_minor),
                CONSTRAINT cattophp_marketing_sale_lines_wallet CHECK (wallet_minor <= paid_minor),
                CONSTRAINT cattophp_marketing_sale_lines_taken_back CHECK (refunded_minor + charged_back_minor <= paid_minor)
            )',
            'CREATE INDEX cattophp_marketing_sale_lines_offer_idx ON cattophp_marketing_sale_lines (offer_type, offer_reference)',
            'CREATE TABLE cattophp_marketing_sale_movements (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                sale_id bigint NOT NULL REFERENCES cattophp_marketing_sales(id) ON DELETE CASCADE,
                kind varchar(10) NOT NULL CHECK (kind IN (\'paid\', \'refund\', \'chargeback\')),
                key varchar(120) NOT NULL CHECK (key <> \'\'),
                amount_minor bigint NOT NULL CHECK (amount_minor >= 0),
                at timestamptz NOT NULL,
                lines jsonb NOT NULL DEFAULT \'{}\'::jsonb CHECK (jsonb_typeof(lines) = \'object\'),
                how varchar(80) NOT NULL DEFAULT \'\',
                CONSTRAINT cattophp_marketing_sale_movements_key UNIQUE (sale_id, key)
            )',
            'CREATE INDEX cattophp_marketing_sale_movements_at_idx ON cattophp_marketing_sale_movements (at)',
            // The journey's events: the sale an event belongs to, so a journey shows an order's events beside the rest.
            'ALTER TABLE cattophp_marketing_events ADD COLUMN sale_id bigint NULL REFERENCES cattophp_marketing_sales(id) ON DELETE SET NULL',
            'CREATE INDEX cattophp_marketing_events_sale_idx ON cattophp_marketing_events (sale_id) WHERE sale_id IS NOT NULL',
            // Connected sites: removed ones stay, with removed_at, so the records that name them keep their name.
            'CREATE TABLE cattophp_marketing_sites (
                key varchar(40) PRIMARY KEY CHECK (key ~ \'^[a-z0-9][a-z0-9-]{0,39}$\'),
                name varchar(120) NOT NULL CHECK (name <> \'\'),
                address varchar(300) NOT NULL CHECK (address ~ \'^https://[^/[:space:]]+(/[^[:space:]]*)?$\'),
                secret text NOT NULL,
                previous_secret text NULL,
                last_sent_at timestamptz NULL,
                last_received_at timestamptz NULL,
                last_checked_at timestamptz NULL,
                clock_apart_seconds integer NULL,
                last_problem varchar(300) NULL,
                last_problem_at timestamptz NULL,
                last_refused varchar(300) NULL,
                last_refused_at timestamptz NULL,
                created_by text NULL,
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now(),
                removed_at timestamptz NULL,
                CONSTRAINT cattophp_marketing_sites_problem_when CHECK ((last_problem IS NULL) = (last_problem_at IS NULL)),
                CONSTRAINT cattophp_marketing_sites_refused_when CHECK ((last_refused IS NULL) = (last_refused_at IS NULL))
            )',
            'CREATE UNIQUE INDEX cattophp_marketing_sites_address_key ON cattophp_marketing_sites (lower(address)) WHERE removed_at IS NULL',
            'CREATE TABLE cattophp_marketing_reports_out (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                site_key varchar(40) NOT NULL REFERENCES cattophp_marketing_sites(key) ON DELETE CASCADE,
                key varchar(200) NOT NULL CHECK (key <> \'\'),
                kind varchar(40) NOT NULL CHECK (kind ~ \'^[a-z][a-z_]{0,39}$\'),
                body jsonb NOT NULL CHECK (jsonb_typeof(body) = \'object\'),
                made_at timestamptz NOT NULL DEFAULT now(),
                attempts integer NOT NULL DEFAULT 0 CHECK (attempts >= 0),
                next_try_at timestamptz NOT NULL DEFAULT now(),
                delivered_at timestamptz NULL,
                gave_up_at timestamptz NULL,
                last_error varchar(300) NULL,
                CONSTRAINT cattophp_marketing_reports_out_key UNIQUE (site_key, key),
                CONSTRAINT cattophp_marketing_reports_out_ended CHECK (delivered_at IS NULL OR gave_up_at IS NULL)
            )',
            'CREATE INDEX cattophp_marketing_reports_out_due_idx ON cattophp_marketing_reports_out (next_try_at) WHERE delivered_at IS NULL AND gave_up_at IS NULL',
            'CREATE INDEX cattophp_marketing_reports_out_made_idx ON cattophp_marketing_reports_out (made_at)',
            'CREATE TABLE cattophp_marketing_reports_in (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                site_key varchar(40) NOT NULL REFERENCES cattophp_marketing_sites(key) ON DELETE CASCADE,
                key varchar(200) NOT NULL CHECK (key <> \'\'),
                kind varchar(40) NOT NULL CHECK (kind ~ \'^[a-z][a-z_]{0,39}$\'),
                received_at timestamptz NOT NULL DEFAULT now(),
                result varchar(16) NOT NULL CHECK (result IN (\'recorded\', \'unknown_click\', \'refused\')),
                CONSTRAINT cattophp_marketing_reports_in_key UNIQUE (site_key, key)
            )',
            'CREATE INDEX cattophp_marketing_reports_in_received_idx ON cattophp_marketing_reports_in (received_at)',
        ];
    }
}
