<?php

declare(strict_types=1);

namespace CattoPHP\Schema\Steps;

use CattoPHP\Schema\SqlStep;

/**
 * The Inbox's records: each conversation (a message from the contact form, with its reference, its folder and what the
 * spam check found), each item of a conversation (the message, the acknowledgement, replies and drafts, answers from the
 * mailbox), the word filter's counts and what each message taught it, the blocked senders, and where the mailbox stood
 * when it was last read. A person is their account in text.
 */
final class Step202611122300Inbox extends SqlStep
{
    public function id(): string
    {
        return '202611122300-inbox';
    }

    public function describe(): string
    {
        return 'The Inbox: conversations and their items, the spam filter, blocked senders and the mailbox';
    }

    protected function statements(): array
    {
        return [
            'CREATE TABLE cattophp_inbox_conversations (
                id bigserial PRIMARY KEY,
                reference varchar(20) NOT NULL UNIQUE,
                reason varchar(40) NOT NULL,
                sender_name varchar(120) NOT NULL,
                sender_email varchar(254) NOT NULL,
                account text NULL,
                account_reference varchar(40) NULL,
                details jsonb NOT NULL DEFAULT \'{}\'::jsonb,
                message text NOT NULL CHECK (char_length(message) BETWEEN 1 AND 5000),
                created_at timestamptz NOT NULL DEFAULT now(),
                emailed_at timestamptz NULL,
                acknowledged_at timestamptz NULL,
                answered_at timestamptz NULL,
                answered_by text NULL,
                folder text NOT NULL DEFAULT \'inbox\' CHECK (folder IN (\'inbox\', \'spam\', \'trash\')),
                folder_before_trash text NULL CHECK (folder_before_trash IS NULL OR folder_before_trash IN (\'inbox\', \'spam\')),
                trashed_at timestamptz NULL,
                spam_score integer NULL CHECK (spam_score IS NULL OR spam_score BETWEEN 0 AND 100),
                spam_signals jsonb NOT NULL DEFAULT \'[]\'::jsonb,
                spam_verdict text NULL CHECK (spam_verdict IS NULL OR spam_verdict IN (\'spam\', \'ham\')),
                read_at timestamptz NULL,
                unread_answer boolean NOT NULL DEFAULT false,
                last_activity_at timestamptz NOT NULL DEFAULT now(),
                sender_ip text NULL,
                sender_agent text NULL,
                seconds_on_page integer NULL,
                sender_country text NULL,
                CONSTRAINT cattophp_inbox_conversations_trash_check CHECK ((folder = \'trash\') = (trashed_at IS NOT NULL))
            )',
            'CREATE INDEX cattophp_inbox_conversations_unanswered_idx ON cattophp_inbox_conversations (created_at) WHERE answered_at IS NULL',
            'CREATE INDEX cattophp_inbox_conversations_created_idx ON cattophp_inbox_conversations (created_at DESC)',
            'CREATE INDEX cattophp_inbox_conversations_folder_idx ON cattophp_inbox_conversations (folder, last_activity_at DESC)',
            'CREATE TABLE cattophp_inbox_items (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                public_id uuid NOT NULL UNIQUE DEFAULT gen_random_uuid(),
                conversation_id bigint NOT NULL REFERENCES cattophp_inbox_conversations(id) ON DELETE CASCADE,
                direction text NOT NULL CHECK (direction IN (\'received\', \'sent\')),
                kind text NOT NULL CHECK (kind IN (\'message\', \'acknowledgement\', \'reply\', \'answer\')),
                status text NOT NULL CHECK (status IN (\'received\', \'draft\', \'sent\', \'failed\')),
                format text NOT NULL DEFAULT \'plain\' CHECK (format IN (\'plain\', \'html\')),
                subject text NOT NULL DEFAULT \'\',
                from_name text NOT NULL DEFAULT \'\',
                from_email text NOT NULL DEFAULT \'\',
                to_email text NOT NULL DEFAULT \'\',
                body_text text NOT NULL DEFAULT \'\',
                body_html text NULL,
                attachments jsonb NOT NULL DEFAULT \'[]\'::jsonb,
                message_id text NULL UNIQUE,
                in_reply_to text NULL,
                mark_answered boolean NOT NULL DEFAULT true,
                written_by text NULL,
                error text NULL,
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now(),
                sent_at timestamptz NULL,
                received_at timestamptz NULL,
                trashed_at timestamptz NULL,
                CONSTRAINT cattophp_inbox_items_direction_status CHECK ((direction = \'received\') = (status = \'received\')),
                CONSTRAINT cattophp_inbox_items_trash_check CHECK (trashed_at IS NULL OR status = \'draft\')
            )',
            'CREATE INDEX cattophp_inbox_items_conversation_idx ON cattophp_inbox_items (conversation_id, created_at)',
            'CREATE INDEX cattophp_inbox_items_status_idx ON cattophp_inbox_items (status, updated_at DESC)',
            'CREATE TABLE cattophp_inbox_spam_tokens (
                token text PRIMARY KEY,
                spam_count integer NOT NULL DEFAULT 0 CHECK (spam_count >= 0),
                ham_count integer NOT NULL DEFAULT 0 CHECK (ham_count >= 0),
                updated_at timestamptz NOT NULL DEFAULT now()
            )',
            'CREATE TABLE cattophp_inbox_spam_training (
                conversation_id bigint PRIMARY KEY REFERENCES cattophp_inbox_conversations(id) ON DELETE CASCADE,
                verdict text NOT NULL CHECK (verdict IN (\'spam\', \'ham\')),
                tokens jsonb NOT NULL,
                trained_by text NULL,
                trained_at timestamptz NOT NULL DEFAULT now()
            )',
            'CREATE TABLE cattophp_inbox_blocked_senders (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                value text NOT NULL UNIQUE,
                kind text NOT NULL CHECK (kind IN (\'email\', \'domain\')),
                created_by text NULL,
                created_at timestamptz NOT NULL DEFAULT now()
            )',
            'CREATE TABLE cattophp_inbox_mailbox (
                id smallint PRIMARY KEY DEFAULT 1 CHECK (id = 1),
                state jsonb NOT NULL DEFAULT \'{}\'::jsonb,
                updated_at timestamptz NOT NULL DEFAULT now()
            )',
        ];
    }
}
