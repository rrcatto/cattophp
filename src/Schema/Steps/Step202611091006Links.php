<?php

declare(strict_types=1);

namespace CattoPHP\Schema\Steps;

use CattoPHP\Schema\SqlStep;

/**
 * Links that work once, of every purpose, in one table: sign-in links become the purpose sign_in. A link may be for an
 * address with no account yet (a registration), carries what it needs, and notes where it was asked for from, so
 * requests are counted for an address and for a place. A link's number is given unless the project gives its own (an
 * application moving its links in keeps theirs).
 */
final class Step202611091006Links extends SqlStep
{
    public function id(): string
    {
        return '202611091006-links';
    }

    public function describe(): string
    {
        return 'Links that work once';
    }

    protected function statements(): array
    {
        return [
            'CREATE TABLE cattophp_links (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                token_hash text NOT NULL UNIQUE,
                purpose text NOT NULL,
                email text NULL,
                account_id text NULL,
                context jsonb NOT NULL DEFAULT \'{}\'::jsonb,
                requested_from text NULL,
                created_at timestamptz NOT NULL,
                expires_at timestamptz NOT NULL,
                used_at timestamptz NULL
            )',
            'CREATE INDEX cattophp_links_email ON cattophp_links (email, created_at DESC)',
            'CREATE INDEX cattophp_links_from ON cattophp_links (requested_from, created_at DESC)',
            'CREATE INDEX cattophp_links_account ON cattophp_links (account_id, purpose)',
            'CREATE INDEX cattophp_links_expires ON cattophp_links (expires_at)',
            "INSERT INTO cattophp_links (token_hash, purpose, account_id, context, created_at, expires_at, used_at)
                SELECT token_hash, 'sign_in', account_id, CASE WHEN return_path IS NULL THEN '{}'::jsonb ELSE jsonb_build_object('return_path', return_path) END,
                       created_at, expires_at, used_at
                FROM cattophp_sign_in_links",
            'DROP TABLE cattophp_sign_in_links',
        ];
    }
}
