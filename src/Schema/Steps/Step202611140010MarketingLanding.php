<?php

declare(strict_types=1);

namespace CattoPHP\Schema\Steps;

use CattoPHP\Schema\SqlStep;

/**
 * The Campaign Marketing Manager's landing pages: each page (a campaign's or an offer's, never both, never neither), its
 * sections (a flat list, the hero first and full width), its kept versions (every published state, never changed while the
 * page exists), saved templates, and the journey's events (a landing page opened, an offer's button pressed; later steps
 * add their kinds to the same table). A section's kind is any key, since a project adds its own kinds, so only the hero's
 * rules are the database's; the other kinds a page holds once are kept to by the page's row lock.
 */
final class Step202611140010MarketingLanding extends SqlStep
{
    public function id(): string
    {
        return '202611140010-marketing-landing';
    }

    public function describe(): string
    {
        return 'The Campaign Marketing Manager: landing pages, their sections, kept versions and templates, and the journey\'s events';
    }

    protected function statements(): array
    {
        return [
            'CREATE TABLE cattophp_marketing_landing_pages (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reference varchar(12) NOT NULL UNIQUE,
                campaign_id bigint NULL UNIQUE REFERENCES cattophp_marketing_campaigns(id) ON DELETE RESTRICT,
                offer_type varchar(40) NULL,
                offer_reference varchar(120) NULL,
                slug varchar(120) NULL UNIQUE CHECK (slug IS NULL OR slug ~ \'^[a-z0-9]+(-[a-z0-9]+)*$\'),
                status varchar(16) NOT NULL DEFAULT \'draft\' CHECK (status IN (\'draft\', \'published\')),
                first_published_at timestamptz NULL,
                published_at timestamptz NULL,
                meta_title varchar(120) NULL,
                meta_description varchar(300) NULL,
                share_picture jsonb NULL CHECK (share_picture IS NULL OR jsonb_typeof(share_picture) = \'object\'),
                not_running varchar(16) NOT NULL DEFAULT \'keep\' CHECK (not_running IN (\'keep\', \'note\', \'forward\')),
                not_running_to varchar(2000) NULL,
                created_by text NULL,
                updated_by text NULL,
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT cattophp_marketing_landing_pages_one_owner CHECK ((campaign_id IS NULL) <> (offer_type IS NULL)),
                CONSTRAINT cattophp_marketing_landing_pages_offer CHECK ((offer_type IS NULL) = (offer_reference IS NULL)),
                CONSTRAINT cattophp_marketing_landing_pages_slug CHECK ((offer_type IS NULL) = (slug IS NULL)),
                CONSTRAINT cattophp_marketing_landing_pages_published_when CHECK ((status = \'published\') = (published_at IS NOT NULL) AND (published_at IS NULL OR first_published_at IS NOT NULL))
            )',
            'CREATE UNIQUE INDEX cattophp_marketing_landing_pages_one_per_offer ON cattophp_marketing_landing_pages (offer_type, offer_reference) WHERE offer_type IS NOT NULL',
            'CREATE TABLE cattophp_marketing_landing_sections (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reference varchar(12) NOT NULL UNIQUE,
                landing_page_id bigint NOT NULL REFERENCES cattophp_marketing_landing_pages(id) ON DELETE CASCADE,
                kind varchar(40) NOT NULL CHECK (kind ~ \'^[a-z][a-z0-9_]{0,39}$\'),
                position integer NOT NULL CHECK (position >= 0),
                enabled boolean NOT NULL DEFAULT true,
                unsaved boolean NOT NULL DEFAULT false,
                width varchar(8) NOT NULL DEFAULT \'full\' CHECK (width IN (\'half\', \'full\')),
                shown_when varchar(12) NOT NULL DEFAULT \'always\' CHECK (shown_when IN (\'always\', \'running\', \'not_running\')),
                data jsonb NOT NULL DEFAULT \'{}\'::jsonb CHECK (jsonb_typeof(data) = \'object\'),
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT cattophp_marketing_landing_sections_hero_first CHECK ((kind = \'hero\') = (position = 0)),
                CONSTRAINT cattophp_marketing_landing_sections_hero_full CHECK (kind <> \'hero\' OR width = \'full\'),
                CONSTRAINT cattophp_marketing_landing_sections_position_key UNIQUE (landing_page_id, position) DEFERRABLE INITIALLY IMMEDIATE
            )',
            'CREATE UNIQUE INDEX cattophp_marketing_landing_sections_one_hero ON cattophp_marketing_landing_sections (landing_page_id) WHERE kind = \'hero\'',
            'CREATE INDEX cattophp_marketing_landing_sections_kind_idx ON cattophp_marketing_landing_sections (kind)',
            'CREATE TABLE cattophp_marketing_landing_versions (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                landing_page_id bigint NOT NULL REFERENCES cattophp_marketing_landing_pages(id) ON DELETE CASCADE,
                number integer NOT NULL CHECK (number > 0),
                kind varchar(12) NOT NULL CHECK (kind IN (\'published\', \'unpublished\')),
                at timestamptz NOT NULL DEFAULT now(),
                made_by text NULL,
                what_changed varchar(300) NOT NULL DEFAULT \'\',
                content jsonb NULL,
                CONSTRAINT cattophp_marketing_landing_versions_number UNIQUE (landing_page_id, number),
                CONSTRAINT cattophp_marketing_landing_versions_content CHECK ((kind = \'published\') = (content IS NOT NULL) AND (content IS NULL OR jsonb_typeof(content) = \'object\'))
            )',
            // A kept version is never changed, and goes only with its page (a page never public, which has none).
            'CREATE FUNCTION cattophp_marketing_landing_versions_kept() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN
                IF TG_OP = \'UPDATE\' THEN
                    IF NEW.made_by IS NULL AND OLD.made_by IS NOT NULL AND NEW.id = OLD.id AND NEW.landing_page_id = OLD.landing_page_id AND NEW.number = OLD.number AND NEW.kind = OLD.kind
                        AND NEW.at = OLD.at AND NEW.what_changed = OLD.what_changed AND NEW.content IS NOT DISTINCT FROM OLD.content THEN
                        RETURN NEW;
                    END IF;
                    RAISE EXCEPTION \'A kept version of a landing page is never changed.\';
                END IF;
                IF EXISTS (SELECT 1 FROM cattophp_marketing_landing_pages WHERE id = OLD.landing_page_id) THEN
                    RAISE EXCEPTION \'A kept version of a landing page goes only with its page.\';
                END IF;
                RETURN OLD;
            END $$',
            'CREATE TRIGGER cattophp_marketing_landing_versions_kept BEFORE UPDATE OR DELETE ON cattophp_marketing_landing_versions FOR EACH ROW EXECUTE FUNCTION cattophp_marketing_landing_versions_kept()',
            'CREATE TABLE cattophp_marketing_landing_templates (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reference varchar(12) NOT NULL UNIQUE,
                name varchar(80) NOT NULL,
                note varchar(200) NOT NULL DEFAULT \'\',
                suits varchar(10) NOT NULL DEFAULT \'both\' CHECK (suits IN (\'campaign\', \'offer\', \'both\')),
                sections jsonb NOT NULL CHECK (jsonb_typeof(sections) = \'array\'),
                made_by text NULL,
                made_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now()
            )',
            'CREATE UNIQUE INDEX cattophp_marketing_landing_templates_name ON cattophp_marketing_landing_templates (lower(name))',
            'CREATE TABLE cattophp_marketing_events (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                kind varchar(40) NOT NULL CHECK (kind ~ \'^[a-z][a-z_]{0,39}$\'),
                at timestamptz NOT NULL DEFAULT now(),
                visitor_id bigint NULL REFERENCES cattophp_marketing_visitors(id) ON DELETE SET NULL,
                account text NULL,
                campaign_id bigint NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE CASCADE,
                publication_id bigint NULL REFERENCES cattophp_marketing_publications(id) ON DELETE SET NULL,
                touch_id bigint NULL REFERENCES cattophp_marketing_touches(id) ON DELETE SET NULL,
                landing_page_id bigint NULL REFERENCES cattophp_marketing_landing_pages(id) ON DELETE SET NULL,
                offer_type varchar(40) NULL,
                offer_reference varchar(120) NULL,
                detail jsonb NOT NULL DEFAULT \'{}\'::jsonb CHECK (jsonb_typeof(detail) = \'object\'),
                country varchar(2) NOT NULL DEFAULT \'\',
                do_not_track boolean NOT NULL DEFAULT false,
                idempotency_key varchar(120) NULL UNIQUE,
                origin_site varchar(120) NULL,
                origin_reference varchar(120) NULL
            )',
            'CREATE INDEX cattophp_marketing_events_campaign_idx ON cattophp_marketing_events (campaign_id, at)',
            'CREATE INDEX cattophp_marketing_events_page_idx ON cattophp_marketing_events (landing_page_id, at)',
            'CREATE INDEX cattophp_marketing_events_visitor_idx ON cattophp_marketing_events (visitor_id, at) WHERE visitor_id IS NOT NULL',
            'CREATE INDEX cattophp_marketing_events_account_idx ON cattophp_marketing_events (account) WHERE account IS NOT NULL',
            'CREATE INDEX cattophp_marketing_events_at_idx ON cattophp_marketing_events (at)',
        ];
    }
}
