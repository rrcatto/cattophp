<?php

declare(strict_types=1);

namespace CattoPHP\Schema\Steps;

use CattoPHP\Schema\SqlStep;

/**
 * Sign-ins kept in the database: each by its cookie's hash, the account and the address it signed in with, where it came
 * from and in which browser, when it began, was last seen and runs out, and when it was ended, so a person can see their
 * sign-ins and end one, and an administrator can end all of someone's at once. A sign-in's number is given unless the
 * project gives its own (an application moving its sign-ins in keeps theirs).
 */
final class Step202611091007Sessions extends SqlStep
{
    public function id(): string
    {
        return '202611091007-sessions';
    }

    public function describe(): string
    {
        return 'Sign-ins kept in the database';
    }

    protected function statements(): array
    {
        return [
            'CREATE TABLE cattophp_sessions (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                token_hash text NOT NULL UNIQUE,
                public_id text NOT NULL UNIQUE,
                account_id text NOT NULL,
                email text NULL,
                requested_from text NULL,
                user_agent text NULL,
                started_at timestamptz NOT NULL,
                last_seen_at timestamptz NOT NULL,
                expires_at timestamptz NOT NULL,
                ended_at timestamptz NULL
            )',
            'CREATE INDEX cattophp_sessions_account ON cattophp_sessions (account_id, started_at DESC)',
            'CREATE INDEX cattophp_sessions_expires ON cattophp_sessions (expires_at)',
        ];
    }
}
