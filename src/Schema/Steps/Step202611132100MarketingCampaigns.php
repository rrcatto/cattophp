<?php

declare(strict_types=1);

namespace CattoPHP\Schema\Steps;

use CattoPHP\Schema\SqlStep;

/**
 * The Campaign Marketing Manager's first records: the channels a campaign is published on (given the usual ones to start),
 * the campaigns with the offers each promotes, their adverts, each place a campaign was published (a publication, with
 * its cost and its code in the tracking link), other spend, the visitors who came by a tracking link and each time a
 * tracking link was opened (a touch). Money is whole minor units of the installation's one currency; a person is their
 * account in text; codes are lower-case. A campaign's history is the activity log's, by its code.
 */
final class Step202611132100MarketingCampaigns extends SqlStep
{
    /** The channels a new installation starts with: key, label, link prefix, icon, in this order. */
    public const STARTING_CHANNELS = [
        ['facebook', 'Facebook', 'fb', 'users'],
        ['instagram', 'Instagram', 'ig', 'camera'],
        ['whatsapp', 'WhatsApp', 'wa', 'message-circle'],
        ['linkedin', 'LinkedIn', 'li', 'briefcase'],
        ['email', 'Email', 'em', 'mail'],
        ['x', 'X', 'x', 'hash'],
        ['youtube', 'YouTube', 'yt', 'circle-play'],
        ['tiktok', 'TikTok', 'tt', 'music'],
        ['telegram', 'Telegram', 'tg', 'send'],
        ['search-adverts', 'Search adverts', 'sa', 'search'],
        ['print', 'Print', 'pr', 'printer'],
        ['other', 'Other', 'ot', 'megaphone'],
    ];

    public function id(): string
    {
        return '202611132100-marketing-campaigns';
    }

    public function describe(): string
    {
        return 'The Campaign Marketing Manager: channels, campaigns, adverts, publications, spend, visitors and touches';
    }

    protected function statements(): array
    {
        $channels = [];
        foreach (self::STARTING_CHANNELS as $position => [$key, $label, $prefix, $icon]) {
            $channels[] = sprintf("('%s', '%s', '%s', '%s', %d)", $key, $label, $prefix, $icon, ($position + 1) * 10);
        }

        return [
            'CREATE TABLE cattophp_marketing_channels (
                key varchar(40) PRIMARY KEY CHECK (key ~ \'^[a-z0-9][a-z0-9-]{0,39}$\'),
                label varchar(60) NOT NULL,
                link_prefix varchar(3) NOT NULL UNIQUE CHECK (link_prefix ~ \'^[a-z]{1,3}$\'),
                icon varchar(64) NOT NULL,
                position integer NOT NULL DEFAULT 0,
                active boolean NOT NULL DEFAULT true,
                created_at timestamptz NOT NULL DEFAULT now()
            )',
            'INSERT INTO cattophp_marketing_channels (key, label, link_prefix, icon, position) VALUES ' . implode(', ', $channels),
            'CREATE TABLE cattophp_marketing_campaigns (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code varchar(40) NOT NULL UNIQUE CHECK (code ~ \'^[a-z0-9][a-z0-9-]{1,39}$\'),
                former_codes jsonb NOT NULL DEFAULT \'[]\'::jsonb,
                name varchar(120) NOT NULL,
                description text NOT NULL DEFAULT \'\',
                objective text NOT NULL DEFAULT \'\',
                status varchar(10) NOT NULL DEFAULT \'draft\' CHECK (status IN (\'draft\', \'active\', \'paused\', \'archived\')),
                status_before_archive varchar(10) NULL CHECK (status_before_archive IS NULL OR status_before_archive IN (\'draft\', \'active\', \'paused\')),
                starts_at timestamptz NULL,
                ends_at timestamptz NULL,
                budget_minor bigint NULL CHECK (budget_minor IS NULL OR budget_minor >= 0),
                destination varchar(2000) NOT NULL DEFAULT \'/\',
                promotion varchar(120) NULL,
                created_by text NULL,
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT cattophp_marketing_campaigns_dates CHECK (starts_at IS NULL OR ends_at IS NULL OR ends_at > starts_at)
            )',
            'CREATE INDEX cattophp_marketing_campaigns_status_idx ON cattophp_marketing_campaigns (status, updated_at DESC)',
            'CREATE TABLE cattophp_marketing_campaign_offers (
                campaign_id bigint NOT NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE CASCADE,
                offer_type varchar(40) NOT NULL,
                offer_reference varchar(120) NOT NULL,
                label varchar(200) NOT NULL,
                position integer NOT NULL DEFAULT 0,
                PRIMARY KEY (campaign_id, offer_type, offer_reference)
            )',
            'CREATE TABLE cattophp_marketing_adverts (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reference varchar(12) NOT NULL UNIQUE,
                campaign_id bigint NOT NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE CASCADE,
                name varchar(120) NOT NULL,
                kind varchar(10) NOT NULL CHECK (kind IN (\'words\', \'picture\', \'video\')),
                headline varchar(200) NOT NULL DEFAULT \'\',
                words text NOT NULL DEFAULT \'\',
                media_address varchar(2000) NULL,
                picture varchar(80) NULL,
                notes text NOT NULL DEFAULT \'\',
                retired_at timestamptz NULL,
                created_by text NULL,
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now()
            )',
            'CREATE INDEX cattophp_marketing_adverts_campaign_idx ON cattophp_marketing_adverts (campaign_id, created_at)',
            'CREATE TABLE cattophp_marketing_publications (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                campaign_id bigint NOT NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE CASCADE,
                channel_key varchar(40) NOT NULL REFERENCES cattophp_marketing_channels(key),
                advert_id bigint NULL REFERENCES cattophp_marketing_adverts(id) ON DELETE SET NULL,
                code varchar(12) NOT NULL CHECK (code ~ \'^[a-z0-9]{1,12}$\'),
                place varchar(200) NOT NULL DEFAULT \'\',
                published_on date NULL,
                published_address varchar(2000) NULL,
                cost_minor bigint NOT NULL DEFAULT 0 CHECK (cost_minor >= 0),
                destination varchar(2000) NULL,
                notes text NOT NULL DEFAULT \'\',
                source_type varchar(40) NULL,
                source_reference varchar(120) NULL,
                retired_at timestamptz NULL,
                created_by text NULL,
                created_at timestamptz NOT NULL DEFAULT now(),
                updated_at timestamptz NOT NULL DEFAULT now(),
                CONSTRAINT cattophp_marketing_publications_code UNIQUE (campaign_id, code)
            )',
            'CREATE INDEX cattophp_marketing_publications_channel_idx ON cattophp_marketing_publications (channel_key)',
            'CREATE INDEX cattophp_marketing_publications_source_idx ON cattophp_marketing_publications (source_type, source_reference) WHERE source_type IS NOT NULL',
            'CREATE TABLE cattophp_marketing_spend (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reference varchar(12) NOT NULL UNIQUE,
                campaign_id bigint NOT NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE CASCADE,
                spent_on date NOT NULL,
                amount_minor bigint NOT NULL CHECK (amount_minor > 0),
                note varchar(300) NOT NULL DEFAULT \'\',
                created_by text NULL,
                created_at timestamptz NOT NULL DEFAULT now()
            )',
            'CREATE INDEX cattophp_marketing_spend_campaign_idx ON cattophp_marketing_spend (campaign_id, spent_on)',
            'CREATE TABLE cattophp_marketing_visitors (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                token char(32) NULL UNIQUE CHECK (token IS NULL OR token ~ \'^[0-9a-f]{32}$\'),
                first_seen_at timestamptz NOT NULL DEFAULT now(),
                last_seen_at timestamptz NOT NULL DEFAULT now(),
                account text NULL,
                country varchar(2) NOT NULL DEFAULT \'\',
                device varchar(10) NOT NULL DEFAULT \'unknown\' CHECK (device IN (\'desktop\', \'phone\', \'tablet\', \'unknown\')),
                anonymised_at timestamptz NULL,
                CONSTRAINT cattophp_marketing_visitors_anonymous CHECK (anonymised_at IS NULL OR (token IS NULL AND account IS NULL))
            )',
            'CREATE INDEX cattophp_marketing_visitors_account_idx ON cattophp_marketing_visitors (account) WHERE account IS NOT NULL',
            'CREATE INDEX cattophp_marketing_visitors_last_seen_idx ON cattophp_marketing_visitors (last_seen_at)',
            'CREATE TABLE cattophp_marketing_touches (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                visitor_id bigint NULL REFERENCES cattophp_marketing_visitors(id) ON DELETE SET NULL,
                campaign_id bigint NOT NULL REFERENCES cattophp_marketing_campaigns(id) ON DELETE CASCADE,
                publication_id bigint NULL REFERENCES cattophp_marketing_publications(id) ON DELETE CASCADE,
                source varchar(64) NOT NULL DEFAULT \'\',
                utm_source varchar(64) NULL,
                utm_medium varchar(64) NULL,
                utm_campaign varchar(64) NULL,
                utm_term varchar(64) NULL,
                utm_content varchar(64) NULL,
                at timestamptz NOT NULL DEFAULT now(),
                ip text NULL,
                country varchar(2) NOT NULL DEFAULT \'\',
                referrer_host varchar(255) NULL,
                agent varchar(10) NOT NULL CHECK (agent IN (\'person\', \'preview\', \'search\', \'ai\', \'bot\')),
                counted boolean NOT NULL,
                not_counted_because varchar(12) NULL CHECK (not_counted_because IS NULL OR not_counted_because IN (\'preview\', \'search\', \'ai\', \'bot\', \'same_visit\', \'draft\', \'paused\', \'archived\', \'not_started\', \'ended\')),
                first_for_visitor boolean NOT NULL DEFAULT false,
                do_not_track boolean NOT NULL DEFAULT false,
                landing varchar(2000) NOT NULL,
                origin_site varchar(120) NULL,
                origin_reference varchar(120) NULL,
                CONSTRAINT cattophp_marketing_touches_counted CHECK (counted = (not_counted_because IS NULL))
            )',
            'CREATE INDEX cattophp_marketing_touches_at_idx ON cattophp_marketing_touches (at)',
            'CREATE INDEX cattophp_marketing_touches_campaign_idx ON cattophp_marketing_touches (campaign_id, at)',
            'CREATE INDEX cattophp_marketing_touches_publication_idx ON cattophp_marketing_touches (publication_id) WHERE publication_id IS NOT NULL',
            'CREATE INDEX cattophp_marketing_touches_visitor_idx ON cattophp_marketing_touches (visitor_id, at) WHERE visitor_id IS NOT NULL',
            'CREATE INDEX cattophp_marketing_touches_ip_idx ON cattophp_marketing_touches (at) WHERE ip IS NOT NULL',
            'CREATE UNIQUE INDEX cattophp_marketing_touches_origin_idx ON cattophp_marketing_touches (origin_site, origin_reference) WHERE origin_site IS NOT NULL AND origin_reference IS NOT NULL',
        ];
    }
}
